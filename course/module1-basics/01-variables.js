// ============================================
// ПЕРЕМЕННЫЕ В JAVASCRIPT
// ============================================

// JavaScript предоставляет три способа объявления переменных: var, let, const

// --------------------------------------------
// 1. VAR (старый способ, не рекомендуется)
// --------------------------------------------

// Объявление переменной с использованием var
var oldStyleVariable = "Я переменная var";

// var имеет функциональную область видимости
var globalVar = "Глобальная переменная";

// Переменную var можно переопределить
var redeclaredVar = "Первое значение";
var redeclaredVar = "Второе значение"; // Не будет ошибки

console.log("var пример:", redeclaredVar); // Выводит: Второе значение

// --------------------------------------------
// 2. LET (современный способ для изменяемых переменных)
// --------------------------------------------

// Объявление переменной с использованием let
let modernVariable = "Я переменная let";

// let имеет блочную область видимости
let blockScopedVariable = "Внешняя область";

// Можно изменить значение
blockScopedVariable = "Изменённое значение";

console.log("let пример:", blockScopedVariable); // Выводит: Изменённое значение

// Нельзя переопределить в той же области видимости
// let blockScopedVariable = "Попытка переопределить"; // Ошибка!

// --------------------------------------------
// 3. CONST (для констант)
// --------------------------------------------

// Объявление константы
const CONSTANT_VALUE = "Я константа";

console.log("const пример:", CONSTANT_VALUE); // Выводит: Я константа

// Нельзя переназначить константу
// CONSTANT_VALUE = "Новое значение"; // Ошибка!

// Однако, если const содержит объект или массив, можно изменить их содержимое
const constantObject = { name: "Иван" };
constantObject.name = "Пётр"; // Это допустимо
console.log("Изменённый объект:", constantObject); // Выводит: { name: 'Пётр' }

// Но нельзя переназначить сам объект
// constantObject = { name: "Мария" }; // Ошибка!

// --------------------------------------------
// 4. ОБЛАСТЬ ВИДИМОСТИ (Scope)
// --------------------------------------------

// Глобальная область видимости
let globalScope = "Доступна везде";

// Функциональная область видимости
function demonstrateScope() {
  // Локальная переменная внутри функции
  let functionScope = "Доступна только в функции";

  console.log("Внутри функции:", functionScope);
  console.log("Глобальная из функции:", globalScope);
}

// Вызов функции
demonstrateScope();

// console.log(functionScope); // Ошибка! functionScope не доступна здесь

// Блочная область видимости
if (true) {
  // Переменная доступна только внутри блока
  let blockVariable = "Доступна только в блоке if";
  console.log("Внутри блока:", blockVariable);
}

// console.log(blockVariable); // Ошибка! blockVariable не доступна здесь

// --------------------------------------------
// 5. ИМЕНОВАНИЕ ПЕРЕМЕННЫХ
// --------------------------------------------

// Правильные имена переменных:
let userName = "camelCase - рекомендуемый стиль";
let user_name = "snake_case - допустимо, но не рекомендуется в JS";
let UserName = "PascalCase - обычно для классов";
let _privateVariable = "Начало с подчёркивания - условное обозначение приватности";
let $jqueryStyle = "Начало с $ - часто используется в jQuery";

// Константы часто пишут заглавными буквами
const MAX_USERS = 100;
const API_KEY = "secret-key-12345";

// Неправильные имена (вызовут ошибку):
// let 123number = "Не может начинаться с цифры"; // Ошибка!
// let my-variable = "Дефис не разрешён"; // Ошибка!
// let let = "Нельзя использовать зарезервированные слова"; // Ошибка!

// --------------------------------------------
// 6. HOISTING (Всплытие)
// --------------------------------------------

// var поднимается (hoisting)
console.log("Всплытие var:", hoistedVar); // Выводит: undefined (не ошибка!)
var hoistedVar = "Я всплыл";

// let и const не всплывают так же, как var
// console.log(hoistedLet); // Ошибка: Cannot access before initialization
let hoistedLet = "Я не всплыл";

// --------------------------------------------
// 7. ПРАКТИЧЕСКИЕ ПРИМЕРЫ
// --------------------------------------------

// Счётчик
let counter = 0;
counter = counter + 1; // Увеличение на 1
counter++; // Сокращённая форма увеличения на 1
console.log("Счётчик:", counter); // Выводит: 2

// Обмен значениями (без временной переменной)
let a = 5;
let b = 10;
[a, b] = [b, a]; // Деструктуризация для обмена
console.log("a:", a, "b:", b); // Выводит: a: 10 b: 5

// Множественное объявление
let x = 1, y = 2, z = 3;
console.log("x, y, z:", x, y, z); // Выводит: 1 2 3

